void
puls_i18n_set_lang (PulsLang lang)
{
    current_lang = lang;
}

PulsLang
puls_i18n_get_lang (void)
{
    return current_lang;
}

const gchar *
puls_i18n_get (PulsStringId id)
{
    if (id < 0 || id >= PULS_STR_COUNT)
        return "";
    if (current_lang == PULS_LANG_TR) {
        const gchar *s = strings_tr[id];
        return s ? s : strings_en[id];
    }
    const gchar *s = strings_en[id];
    return s ? s : "";
}
